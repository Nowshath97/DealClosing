-- Database-driven entity review tasks. Run after normalized accounts, fund_closes,
-- fund_allocations, task_activity_map and the close-master migration.
begin;
alter table public.task add column if not exists is_applicable boolean not null default true;
create table if not exists public.entity_review_task_rule (
  id integer generated by default as identity primary key,
  entity_flag varchar(100) not null unique,
  task_id integer not null references public.ref_task_name(id),
  activity_id integer not null references public.ref_deal_activity(id),
  is_active boolean not null default true
);
-- Reuse existing review task references when possible; create only missing ones.
do $rules$
declare item record; task_ref integer; activity_ref integer;
begin
  lock table public.ref_task_name in share row exclusive mode;
  select id into activity_ref from public.ref_deal_activity
    where regexp_replace(lower(value),'[^a-z]','','g')='riskcompliance' order by id limit 1;
  if activity_ref is null then raise exception 'Risk & Compliance activity must be configured first.'; end if;
  for item in select * from (values
    ('IsAmgoReviewRequired','Complete AMGO Pre-Commitment Review','amgo'),
    ('IsLuxReviewRequired','Complete Lux Pre-Commitment Review','lux'),
    ('IsAddtnlAMLReviewRequired','Complete Additional AML Review','aml')
  ) options(flag,label,review_key) loop
    select id into task_ref from public.ref_task_name
    where (item.review_key in ('amgo','lux') and regexp_replace(lower(value),'[^a-z]','','g') like '%'||item.review_key||'%precommit%')
       or (item.review_key='aml' and regexp_replace(lower(value),'[^a-z]','','g') in ('completeadditionalamlreview','additionalamlreview','completeaddtnlamlreview','addtnlamlreview'))
    order by id limit 1;
    if task_ref is null then
      insert into public.ref_task_name(id,value,sort_order) overriding system value
        values((select coalesce(max(id),0)+1 from public.ref_task_name),item.label,100) returning id into task_ref;
    end if;
    insert into public.entity_review_task_rule(entity_flag,task_id,activity_id) values(item.flag,task_ref,activity_ref)
      on conflict(entity_flag) do nothing;
    insert into public.task_activity_map(task_id,activity_id) values(task_ref,activity_ref) on conflict do nothing;
  end loop;
end $rules$;

create or replace function public.sync_entity_review_tasks(p_deal varchar,p_close integer default null)
returns void language plpgsql as $$
declare rule record; needed boolean; primary_deal boolean; pending_status integer;
begin
  select regexp_replace(lower(t.value),'[^a-z]','','g') in ('primary','primaries') into primary_deal
    from public.deal d join public.ref_deal_type t on t.id=d.type where d.deal_code=p_deal;
  -- Primary reviews only exist at close level; other investment types stay deal-level.
  if coalesce(primary_deal,false) <> (p_close is not null) then return; end if;
  if p_close is not null and not exists(select 1 from public.fund_closes where id=p_close and deal_code=p_deal) then return; end if;
  perform pg_advisory_xact_lock(hashtext(p_deal),coalesce(p_close,0));
  select id into pending_status from public.ref_task_status where regexp_replace(lower(value),'[^a-z]','','g')='notstarted' order by id limit 1;
  if pending_status is null then raise exception 'Not Started task status must be configured.'; end if;
  for rule in select * from public.entity_review_task_rule loop
    if primary_deal then
      select exists(
        select 1 from public.fund_closes c
        cross join lateral jsonb_each(coalesce(c.editor_data->'accounts','{}'::jsonb)) account
        cross join lateral jsonb_array_elements(coalesce(account.value->'allocationMappings','[]'::jsonb)) mapping
        join public.client_account a on a.account_name=account.key and a.is_active
        join public.client_entity_map m on m.client_id=a.id and m.is_active
        join public.entity e on e."Id"=m.entity_id
        where c.id=p_close and c.deal_code=p_deal
          and (case when nullif(mapping->>'entityId','') is not null
            then e."Id"::text=mapping->>'entityId' else coalesce(nullif(btrim(to_jsonb(e)->>'name'),''),nullif(btrim(e."EntityName"),''))=mapping->>'allottingEntity' end)
          and coalesce(e."IsActive",1)=1 and coalesce(e."IsDeleted",0)=0
          and to_jsonb(e)->>rule.entity_flag in ('1','true')
      ) into needed;
    else
      select exists(select 1 from public.fund_allocations f join public.entity e on e."Id"=f.entity_id
        where f.deal_code=p_deal and f.fund_close_id is null and coalesce(e."IsActive",1)=1
          and coalesce(e."IsDeleted",0)=0 and to_jsonb(e)->>rule.entity_flag in ('1','true')) into needed;
    end if;
    needed:=needed and rule.is_active;
    -- Preserve answers, completion and task IDs when selections change.
    update public.task set is_applicable=needed where deal_code=p_deal and close_id is not distinct from p_close and task_id=rule.task_id;
    if needed and not exists(select 1 from public.task where deal_code=p_deal and close_id is not distinct from p_close and task_id=rule.task_id) then
      insert into public.task(deal_code,close_id,task_id,activity_id,status,is_applicable)
        values(p_deal,p_close,rule.task_id,rule.activity_id,pending_status,true);
    end if;
  end loop;
end $$;
create or replace function public.sync_close_entity_reviews() returns trigger language plpgsql as $$
begin perform public.sync_entity_review_tasks(new.deal_code,new.id); return new; end $$;
drop trigger if exists close_entity_reviews on public.fund_closes;
create trigger close_entity_reviews after insert or update of editor_data on public.fund_closes
  for each row execute function public.sync_close_entity_reviews();
create or replace function public.sync_fund_entity_reviews() returns trigger language plpgsql as $$
begin
  if tg_op<>'INSERT' then perform public.sync_entity_review_tasks(old.deal_code,null); end if;
  if tg_op<>'DELETE' then perform public.sync_entity_review_tasks(new.deal_code,null); return new; end if;
  return old;
end $$;
drop trigger if exists fund_entity_reviews on public.fund_allocations;
create trigger fund_entity_reviews after insert or update or delete on public.fund_allocations
  for each row execute function public.sync_fund_entity_reviews();
-- Re-evaluate requirements if entity flags change in the database.
create or replace function public.refresh_changed_entity_reviews() returns trigger language plpgsql as $$
declare scope record;
begin
  for scope in select deal_code,id as close_id from public.fund_closes
    union select distinct deal_code,null::integer from public.fund_allocations loop
    perform public.sync_entity_review_tasks(scope.deal_code,scope.close_id);
  end loop;
  return new;
end $$;
drop trigger if exists entity_flags_review_tasks on public.entity;
create trigger entity_flags_review_tasks after update of "IsAmgoReviewRequired","IsLuxReviewRequired","IsAddtnlAMLReviewRequired","IsActive","IsDeleted" on public.entity
  for each row execute function public.refresh_changed_entity_reviews();
-- Hide legacy deal-level entity reviews for Primary deals, then backfill valid scopes.
update public.task task set is_applicable=false from public.deal d join public.ref_deal_type t on t.id=d.type
where task.deal_code=d.deal_code and task.close_id is null
  and regexp_replace(lower(t.value),'[^a-z]','','g') in ('primary','primaries')
  and task.task_id in(select task_id from public.entity_review_task_rule);
do $backfill$
declare scope record;
begin
  for scope in select deal_code,id as close_id from public.fund_closes
    union select distinct deal_code,null::integer from public.fund_allocations loop
    perform public.sync_entity_review_tasks(scope.deal_code,scope.close_id);
  end loop;
end $backfill$;
alter table public.entity_review_task_rule enable row level security;
grant select on public.entity_review_task_rule to authenticated;
drop policy if exists "app read" on public.entity_review_task_rule;
create policy "app read" on public.entity_review_task_rule for select to authenticated using(true);
notify pgrst,'reload schema';
commit;
