-- Allocation tables for the Initiate Allocations screen, plus access and sample data.
-- Run in Supabase Dashboard -> SQL Editor. Safe to re-run.
--
-- Shape: public.allocation has ONE row per deal (deal_code is the primary key) and holds the deal-level values.
-- A deal has many allocation lines / legal-name mappings / closes / comments / documents, so those live in child
-- tables that point back to allocation.deal_code. Yes/No answers are stored as smallint 1 / 0.
-- Run seed_entities.sql first: lines reference public.entity and public.entity_account_map.

-- 1. HEADER: one row per deal -------------------------------------------------------------------------------
create table if not exists public.allocation (
  deal_code               varchar(50) primary key references public.deal(deal_code) on delete cascade,
  funding_currency        varchar(10),
  total_adjusted_exposure numeric(20,2),
  funding_required        smallint check (funding_required in (0,1)),          -- 1 = Yes, 0 = No
  partial_funding         smallint check (partial_funding in (0,1)),           -- 1 = Yes, 0 = No (null until answered)
  expenses_pct            numeric(9,4),                                        -- "Expenses %" entered on the screen
  expenses_value          numeric(20,2),                                       -- total expenses amount (sum of the lines)
  total_allocated         numeric(20,2),                                       -- sum of line exposures
  total_client_funding    numeric(20,2),                                       -- allocated + expenses
  calculation_override    smallint not null default 0 check (calculation_override in (0,1)),
  aggregators_formed      smallint not null default 0 check (aggregators_formed in (0,1)),
  status                  varchar(20) not null default 'Draft' check (status in ('Draft','Initiated')),
  initiated_by            varchar(255),
  initiated_on            timestamptz,
  created_by              varchar(255),
  created_on              timestamptz not null default now(),
  modified_by             varchar(255),
  modified_on             timestamptz
);

-- 2. LINES: one row per account / entity allocation ---------------------------------------------------------
create table if not exists public.allocation_line (
  id                       integer generated by default as identity primary key,
  deal_code                varchar(50) not null references public.allocation(deal_code) on delete cascade,
  line_no                  smallint,
  account_map_id           integer references public.entity_account_map("Id"),
  client_account           varchar(255) not null,                              -- e.g. 'Acc. 1'
  entity_id                integer references public.entity("Id"),
  is_placeholder           smallint not null default 0 check (is_placeholder in (0,1)),
  adjusted_exposure        numeric(20,2),
  percentage               numeric(9,4),
  expenses_amount          numeric(20,2),
  expenses_overridden      smallint not null default 0 check (expenses_overridden in (0,1)),
  client_funding           numeric(20,2),
  amgo_review_required     smallint check (amgo_review_required in (0,1)),
  lux_review_required      smallint check (lux_review_required in (0,1)),
  additional_aml_review    smallint check (additional_aml_review in (0,1)),
  client_veto              smallint check (client_veto in (0,1)),
  created_on               timestamptz not null default now(),
  -- an entity can only be allocated once per deal (and each entity belongs to one account)
  constraint allocation_line_one_entity_per_deal unique (deal_code, entity_id)
);

-- 3. LEGAL NAME MAPPING: which investment legal name each line goes into ------------------------------------
create table if not exists public.allocation_legal_map (
  id                     integer generated by default as identity primary key,
  deal_code              varchar(50) not null references public.allocation(deal_code) on delete cascade,
  line_id                integer references public.allocation_line(id) on delete cascade,
  investment_legal_name  varchar(255),
  allocation_amount      numeric(20,2),                                         -- "Allocation - Funding Currency"
  created_on             timestamptz not null default now()
);

-- 4. CLOSES ------------------------------------------------------------------------------------------------
create table if not exists public.allocation_close (
  id          integer generated by default as identity primary key,
  deal_code   varchar(50) not null references public.allocation(deal_code) on delete cascade,
  close_date  date,
  close_type  varchar(20) check (close_type in ('Estimate','Final')),           -- the "Final?" dropdown
  created_on  timestamptz not null default now()
);

-- 5. COMMENTS + DOCUMENT METADATA (file contents would go in Supabase Storage; storage_path points to them) ---
create table if not exists public.allocation_comment (
  id           integer generated by default as identity primary key,
  deal_code    varchar(50) not null references public.allocation(deal_code) on delete cascade,
  comment_text text not null,
  created_by   varchar(255),
  created_on   timestamptz not null default now()
);

create table if not exists public.allocation_document (
  id            integer generated by default as identity primary key,
  deal_code     varchar(50) not null references public.allocation(deal_code) on delete cascade,
  file_name     varchar(500) not null,
  file_type     varchar(100),
  storage_path  varchar(1000),
  uploaded_by   varchar(255),
  uploaded_on   timestamptz not null default now()
);

create index if not exists allocation_line_deal_idx       on public.allocation_line(deal_code);
create index if not exists allocation_legal_map_deal_idx  on public.allocation_legal_map(deal_code);
create index if not exists allocation_close_deal_idx      on public.allocation_close(deal_code);

-- 6. ACCESS (POC level: any signed-in user can read and write; tighten before real use) --------------------
do $$
declare t text;
begin
  foreach t in array array['allocation','allocation_line','allocation_legal_map','allocation_close','allocation_comment','allocation_document'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('grant select, insert, update, delete on public.%I to authenticated', t);
    execute format('drop policy if exists "app rw" on public.%I', t);
    execute format('create policy "app rw" on public.%I for all to authenticated using (true) with check (true)', t);
  end loop;
end $$;

-- 7. SAMPLE DATA: fills the two oldest deals in public.deal (needs seed_entities.sql to have been run) --------
do $$
declare
  d1 varchar; d2 varchar;
  l1 int; l2 int; l3 int;
begin
  select deal_code into d1 from public.deal order by created_on, deal_code limit 1;
  select deal_code into d2 from public.deal order by created_on, deal_code offset 1 limit 1;
  if d1 is null or d2 is null then
    raise notice 'Fewer than 2 deals found; skipping sample allocation data.';
    return;
  end if;

  -- Deal 1: funding required, 2.5% expenses, two accounts / entities, fully initiated
  insert into public.allocation (deal_code, funding_currency, total_adjusted_exposure, funding_required, partial_funding, expenses_pct, expenses_value,
                                 total_allocated, total_client_funding, calculation_override, aggregators_formed, status, initiated_by, initiated_on, created_by)
  values (d1, 'USD', 15000000.00, 1, 0, 2.5, 375000.00, 15000000.00, 15375000.00, 0, 0, 'Initiated', 'seed', now(), 'seed')
  on conflict (deal_code) do nothing;

  if not exists (select 1 from public.allocation_line where deal_code = d1) then
    insert into public.allocation_line (deal_code, line_no, account_map_id, client_account, entity_id, is_placeholder, adjusted_exposure, percentage,
                                        expenses_amount, client_funding, amgo_review_required, lux_review_required, additional_aml_review, client_veto)
    select d1, 1, m."Id", m."ClientAccount", e."Id", 0, 10000000.00, 66.67, 250000.00, 10250000.00,
           coalesce(e."IsAmgoReviewRequired",0), coalesce(e."IsLuxReviewRequired",0), coalesce(e."IsAddtnlAMLReviewRequired",0), coalesce(e."HasVetoRights",0)
    from public.entity_account_map m join public.entity e on e."Id" = m."EntityId" where m."ClientAccount" = 'Acc. 1' and e."Id" = 1;

    insert into public.allocation_line (deal_code, line_no, account_map_id, client_account, entity_id, is_placeholder, adjusted_exposure, percentage,
                                        expenses_amount, client_funding, amgo_review_required, lux_review_required, additional_aml_review, client_veto)
    select d1, 2, m."Id", m."ClientAccount", e."Id", 0, 5000000.00, 33.33, 125000.00, 5125000.00,
           coalesce(e."IsAmgoReviewRequired",0), coalesce(e."IsLuxReviewRequired",0), coalesce(e."IsAddtnlAMLReviewRequired",0), coalesce(e."HasVetoRights",0)
    from public.entity_account_map m join public.entity e on e."Id" = m."EntityId" where m."ClientAccount" = 'Acc. 2' and e."Id" = 5;

    select min(id) into l1 from public.allocation_line where deal_code = d1;
    select max(id) into l2 from public.allocation_line where deal_code = d1;
    insert into public.allocation_legal_map (deal_code, line_id, investment_legal_name, allocation_amount) values
      (d1, l1, 'Legal Name A LP', 10000000.00),
      (d1, l2, 'Legal Name B LP',  5000000.00);
    insert into public.allocation_close (deal_code, close_date, close_type) values (d1, date '2026-12-01', 'Estimate');
    insert into public.allocation_comment (deal_code, comment_text, created_by) values (d1, 'Allocations agreed with the investment team.', 'seed');
    insert into public.allocation_document (deal_code, file_name, file_type, uploaded_by) values (d1, 'allocation-workpaper.xlsx', 'application/vnd.ms-excel', 'seed');
  end if;

  -- Deal 2: no funding, no expenses, one line, still a draft
  insert into public.allocation (deal_code, funding_currency, total_adjusted_exposure, funding_required, partial_funding, expenses_pct, expenses_value,
                                 total_allocated, total_client_funding, status, created_by)
  values (d2, 'USD', 8000000.00, 0, null, 0, 0, 8000000.00, 8000000.00, 'Draft', 'seed')
  on conflict (deal_code) do nothing;

  if not exists (select 1 from public.allocation_line where deal_code = d2) then
    insert into public.allocation_line (deal_code, line_no, account_map_id, client_account, entity_id, is_placeholder, adjusted_exposure, percentage,
                                        expenses_amount, client_funding, amgo_review_required, lux_review_required, additional_aml_review, client_veto)
    select d2, 1, m."Id", m."ClientAccount", e."Id", 0, 8000000.00, 100.00, 0, 8000000.00,
           coalesce(e."IsAmgoReviewRequired",0), coalesce(e."IsLuxReviewRequired",0), coalesce(e."IsAddtnlAMLReviewRequired",0), coalesce(e."HasVetoRights",0)
    from public.entity_account_map m join public.entity e on e."Id" = m."EntityId" where m."ClientAccount" = 'Acc. 3' and e."Id" = 7;

    select min(id) into l3 from public.allocation_line where deal_code = d2;
    insert into public.allocation_legal_map (deal_code, line_id, investment_legal_name, allocation_amount) values (d2, l3, 'Legal Name C LLC', 8000000.00);
    insert into public.allocation_close (deal_code, close_date, close_type) values (d2, date '2027-01-15', 'Final');
  end if;
end $$;

