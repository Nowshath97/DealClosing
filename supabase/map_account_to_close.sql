-- Account-to-close records matching all 28 fields in NDC_MAP_ACCOUNT_TO_CLOSE.
-- Run after allocation_tables.sql and normalize_client_accounts.sql.
-- PostgreSQL names use snake_case; MySQL tinyint(1) fields become boolean.
begin;

-- A close must belong to the deal named on its account mapping.
create unique index if not exists fund_closes_id_deal_unique
  on public.fund_closes(id, deal_code);

create table if not exists public.map_account_to_close (
  id integer generated by default as identity primary key, -- Id
  deal_code varchar(50) not null references public.deal(deal_code), -- DealCode
  client_id integer references public.client_account(id), -- ClientId
  fund_close_id integer, -- FundCloseId -> fund_closes.id
  commitment_currency varchar(10), -- CommitmentCurrency
  amount_invested numeric(19,2), -- AmountInvested
  amount_usd numeric(19,2), -- AmountUSD
  amount_percentage numeric(19,14), -- AmountPercentage
  subject_to_veto varchar(50), -- SubjectToVeto
  veto_rights varchar(50), -- VetoRights
  vetoed_date date, -- VetoedDate
  pm_fit_approved boolean, -- PmFitApproved
  client_approved boolean, -- ClientApproved
  pm_team varchar(500), -- PmTeam
  is_materials_sent boolean, -- IsMaterialsSent
  materials_sent_date date, -- MaterialsSentDate
  is_client_call boolean, -- IsClientCall
  client_call_date date, -- ClientCallDate
  program_manager varchar(50), -- ProgramManager
  is_ic_approved boolean, -- IsICApproved
  ic_approved_date date, -- ICApprovedDate
  status_id varchar(50), -- StatusId (reference lookup not yet supplied)
  is_top_up_account boolean, -- IsTopUpAccount
  updated_by varchar(255), -- UpdatedBy
  updated_date_time timestamp without time zone, -- UpdatedDateTime
  desired_allocations numeric(19,2), -- DesiredAllocations
  expenses_amount numeric(19,2), -- ExpensesAmount
  vintage_year integer, -- VintageYear
  constraint map_account_to_close_close_deal_fk
    foreign key (fund_close_id, deal_code)
    references public.fund_closes(id, deal_code),
  constraint map_account_to_close_account_unique unique (fund_close_id, client_id)
);

-- Only Id and DealCode are mandatory in the source schema. All other fields
-- remain nullable, including unanswered Yes/No values. Do not default them to No.
comment on table public.map_account_to_close is
  'One client account per deal close; normalized equivalent of NDC_MAP_ACCOUNT_TO_CLOSE.';
comment on column public.map_account_to_close.client_id is 'References client_account.id; account names are resolved from the master.';
comment on column public.map_account_to_close.fund_close_id is 'References fund_closes.id; composite foreign key ensures the close belongs to deal_code.';
comment on column public.map_account_to_close.amount_percentage is 'Preserves source decimal(19,14); no assumed 0-1 or 0-100 convention.';
comment on column public.map_account_to_close.status_id is 'Source varchar(50); no foreign key until the account-close status lookup is defined.';

create index if not exists map_account_to_close_deal_idx on public.map_account_to_close(deal_code);
create index if not exists map_account_to_close_client_idx on public.map_account_to_close(client_id);

alter table public.map_account_to_close enable row level security;
grant select, insert, update, delete on public.map_account_to_close to authenticated;
grant usage, select on sequence public.map_account_to_close_id_seq to authenticated;
drop policy if exists "app rw" on public.map_account_to_close;
create policy "app rw" on public.map_account_to_close
  for all to authenticated using (true) with check (true);

notify pgrst, 'reload schema';
commit;
