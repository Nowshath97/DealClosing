create table if not exists public.ref_investment_type_detail (
  id integer generated by default as identity primary key,
  deal_type_id integer not null references public.ref_deal_type(id),
  value varchar(255) not null,
  sort_order integer not null default 0,
  is_active boolean not null default true,
  unique(deal_type_id,value)
);
create table if not exists public.ref_execution_location (
  id integer generated by default as identity primary key,
  value varchar(255) not null unique,
  is_active boolean not null default true
);
insert into public.ref_execution_location(value)
values ('New York'), ('Dallas'), ('London'), ('Hong Kong'), ('Boston')
on conflict(value) do nothing;

-- Match existing reference labels without assuming their numeric IDs.
insert into public.ref_investment_type_detail(deal_type_id,value,sort_order)
select t.id,options.value,options.position
from public.ref_deal_type t join (values
  ('coinvestment','Co-Investment Mid Life',1),
  ('coinvestment','Co-Investment Traditional',2),
  ('coinvestment','Co-Invesment Non Syndicative',3),
  ('secondary','Secondary Direct',1),
  ('secondary','Secondary - GP - Led',2),
  ('secondary','Secondary- LP Interests',3),
  ('primary','Primary Funded',1),
  ('primary','Primary Non Funded',2)
) options(type_key,value,position)
on (case regexp_replace(lower(t.value),'[^a-z]','','g')
  when 'coinvest' then 'coinvestment' when 'coinvestments' then 'coinvestment'
  when 'secondaries' then 'secondary' when 'primaries' then 'primary'
  else regexp_replace(lower(t.value),'[^a-z]','','g') end)=options.type_key
on conflict(deal_type_id,value) do nothing;

alter table public.deal
  add column if not exists investment_type_detail_id integer references public.ref_investment_type_detail(id),
  add column if not exists execution_location varchar(255),
  add column if not exists execution_location_id integer references public.ref_execution_location(id);

-- User schemas may use quoted "Id"/"UserId" instead of lowercase id.
-- Resolve the actual single-column primary key rather than assuming its name.
do $user_keys$
declare
  user_key text;
  user_type text;
  target_column text;
begin
  select a.attname,format_type(a.atttypid,a.atttypmod) into user_key,user_type
  from pg_constraint c join pg_attribute a on a.attrelid=c.conrelid and a.attnum=c.conkey[1]
  where c.conrelid='public.users'::regclass and c.contype='p' and cardinality(c.conkey)=1;
  if user_key is null then
    raise exception 'users needs a single-column primary key. Share its table definition before running this migration.';
  end if;
  if user_type not in ('integer','bigint','smallint') then
    raise exception 'users primary key % has type %. This form currently expects numeric user IDs; share the users schema before migrating.',user_key,user_type;
  end if;
  foreach target_column in array array['relationship_lead','execution_team_member'] loop
    execute format('alter table public.deal add column if not exists %I %s',target_column,user_type);
    if not exists(select 1 from pg_constraint c join pg_attribute a on a.attrelid=c.conrelid and a.attnum=c.conkey[1]
      where c.conrelid='public.deal'::regclass and c.contype='f' and a.attname=target_column
        and c.confrelid='public.users'::regclass) then
      execute format('alter table public.deal add constraint %I foreign key(%I) references public.users(%I)',
        'deal_'||target_column||'_users_fk',target_column,user_key);
    end if;
  end loop;
end $user_keys$;

-- Existing deals can remain unassigned; new deals must have all three fields.
-- Status/task updates on old deals continue to work.
create or replace function public.validate_new_deal_options() returns trigger language plpgsql as $$
declare detail public.ref_investment_type_detail;
begin
  if new.relationship_lead is null or new.execution_team_member is null or nullif(btrim(new.execution_location),'') is null then
    raise exception 'Relationship Lead, Execution Team Member and Execution Location are required.';
  end if;
  new.execution_location := btrim(new.execution_location);
  insert into public.ref_execution_location(value) values(new.execution_location) on conflict(value) do nothing;
  select id into new.execution_location_id from public.ref_execution_location where value=new.execution_location and is_active;
  if new.execution_location_id is null then raise exception 'Execution location is inactive.'; end if;
  if new.investment_type_detail_id is not null then
    select * into detail from public.ref_investment_type_detail where id=new.investment_type_detail_id and deal_type_id=new.type and is_active;
    if not found then raise exception 'Investment type detail must belong to the selected investment type and be active.'; end if;
    new.investment_type_detail := detail.value;
  elsif nullif(btrim(new.investment_type_detail),'') is not null then
    select * into detail from public.ref_investment_type_detail where value=new.investment_type_detail and deal_type_id=new.type and is_active;
    if not found then raise exception 'Unknown investment type detail for the selected investment type.'; end if;
    new.investment_type_detail_id := detail.id;
  end if;
  return new;
end $$;
drop trigger if exists new_deal_options_check on public.deal;
create trigger new_deal_options_check before insert on public.deal for each row execute function public.validate_new_deal_options();

