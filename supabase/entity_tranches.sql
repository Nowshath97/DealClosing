-- One entity owns each tranche; an entity can own any number of tranches.
-- Run after fund_closes.sql / the close-master migration.
begin;
create table if not exists public.entity_tranche (
  id integer generated by default as identity primary key,
  entity_id integer not null references public.entity("Id"),
  name varchar(500) not null unique,
  is_active boolean not null default true,
  created_on timestamptz not null default now(),
  constraint entity_tranche_name_nonempty check(btrim(name)<>''),
  constraint entity_tranche_id_entity_unique unique(id,entity_id)
);
create index if not exists entity_tranche_entity_idx on public.entity_tranche(entity_id);
-- Deterministic mixed sample data. Existing names/ownership are never overwritten.
with entities as (
  select "Id" as entity_id,
    coalesce(nullif(btrim(to_jsonb(e)->>'name'),''),nullif(btrim(e."EntityName"),''),'Entity '||e."Id") as entity_name,
    row_number() over(order by "Id") as position
  from public.entity e where coalesce("IsActive",1)=1 and coalesce("IsDeleted",0)=0
), samples as (
  select entity_id,entity_name || case when position % 3=0 then '' else ' - Tranche A' end as name from entities
  union all
  select entity_id,entity_name || ' - Tranche B' from entities where position % 3<>0
)
insert into public.entity_tranche(entity_id,name) select entity_id,name from samples
on conflict(name) do nothing;

create or replace function public.prevent_tranche_reassignment() returns trigger language plpgsql as $$
begin
  if new.entity_id is distinct from old.entity_id then
    raise exception 'A tranche cannot be reassigned to another entity. Create a separate tranche instead.';
  end if;
  return new;
end $$;
drop trigger if exists prevent_tranche_reassignment on public.entity_tranche;
create trigger prevent_tranche_reassignment before update of entity_id on public.entity_tranche
for each row execute function public.prevent_tranche_reassignment();

-- Validate selected IDs on every close save, including direct API writes.
create or replace function public.validate_close_tranches() returns trigger language plpgsql as $$
declare account record; mapping jsonb;
begin
  for account in select * from jsonb_each(coalesce(new.editor_data->'accounts','{}'::jsonb)) loop
    for mapping in select * from jsonb_array_elements(coalesce(account.value->'allocationMappings','[]'::jsonb)) loop
      if nullif(mapping->>'trancheId','') is not null and not exists(
        select 1 from public.entity_tranche t where t.id::text=mapping->>'trancheId'
          and t.entity_id::text=mapping->>'entityId' and t.is_active
      ) then raise exception 'Selected tranche must be active and belong to the selected entity (account %).',account.key; end if;
    end loop;
  end loop;
  return new;
end $$;
drop trigger if exists validate_close_tranches on public.fund_closes;
create trigger validate_close_tranches before insert or update of editor_data on public.fund_closes
for each row execute function public.validate_close_tranches();
alter table public.entity_tranche enable row level security;
grant select on public.entity_tranche to authenticated;
drop policy if exists "app read" on public.entity_tranche;
create policy "app read" on public.entity_tranche for select to authenticated using(true);
notify pgrst,'reload schema';
commit;
