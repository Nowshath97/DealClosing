-- Run after the deal/task schema and allocation_tables.sql, before the updated frontend.
-- Copies existing task/allocation comments and document metadata without deleting sources.
-- Reruns do not copy the same legacy record twice.
begin;
create table if not exists public.deal_comment (
  id integer generated by default as identity primary key,
  deal_code varchar(50) not null references public.deal(deal_code) on delete cascade,
  task_id integer references public.task(id) on delete set null,
  comment_text text not null,
  created_by varchar(255),
  created_on timestamptz not null default now(),
  client_ref varchar(100),
  unique(deal_code,client_ref),
  legacy_source varchar(50), legacy_id integer,
  unique(legacy_source,legacy_id)
);
create table if not exists public.deal_document (
  id integer generated by default as identity primary key,
  deal_code varchar(50) not null references public.deal(deal_code) on delete cascade,
  task_id integer references public.task(id) on delete set null,
  file_name varchar(500) not null,
  file_type varchar(100), storage_path varchar(1000),
  uploaded_by varchar(255), uploaded_on timestamptz not null default now(),
  client_ref varchar(100),
  unique(deal_code,client_ref),
  legacy_source varchar(50), legacy_id integer,
  unique(legacy_source,legacy_id)
);
create index if not exists deal_comment_deal_idx on public.deal_comment(deal_code,created_on,id);
create index if not exists deal_document_deal_idx on public.deal_document(deal_code,uploaded_on,id);

-- task_id is optional context; deal_code owns the record. Reject context from another deal.
create or replace function public.check_deal_collaboration_task() returns trigger language plpgsql as $$
begin
  if new.task_id is not null and not exists(select 1 from public.task t where t.id=new.task_id and t.deal_code=new.deal_code) then
    raise exception 'The originating task must belong to this deal.';
  end if;
  return new;
end $$;
drop trigger if exists deal_comment_task_check on public.deal_comment;
create trigger deal_comment_task_check before insert or update of task_id,deal_code on public.deal_comment
  for each row execute function public.check_deal_collaboration_task();
drop trigger if exists deal_document_task_check on public.deal_document;
create trigger deal_document_task_check before insert or update of task_id,deal_code on public.deal_document
  for each row execute function public.check_deal_collaboration_task();

do $migration$
begin
  if to_regclass('public.task_comment') is not null then
    insert into public.deal_comment(deal_code,task_id,comment_text,created_by,created_on,legacy_source,legacy_id)
      select t.deal_code,c.task_id,c.comment_text,c.created_by,c.created_on,'task_comment',c.id
      from public.task_comment c join public.task t on t.id=c.task_id
      on conflict(legacy_source,legacy_id) do nothing;
  end if;
  if to_regclass('public.task_document') is not null then
    insert into public.deal_document(deal_code,task_id,file_name,file_type,storage_path,uploaded_by,uploaded_on,legacy_source,legacy_id)
      select t.deal_code,d.task_id,d.file_name,d.file_type,d.storage_path,d.uploaded_by,d.uploaded_on,'task_document',d.id
      from public.task_document d join public.task t on t.id=d.task_id
      on conflict(legacy_source,legacy_id) do nothing;
  end if;
  if to_regclass('public.allocation_comment') is not null then
    insert into public.deal_comment(deal_code,comment_text,created_by,created_on,legacy_source,legacy_id)
      select deal_code,comment_text,created_by,created_on,'allocation_comment',id from public.allocation_comment
      on conflict(legacy_source,legacy_id) do nothing;
  end if;
  if to_regclass('public.allocation_document') is not null then
    insert into public.deal_document(deal_code,file_name,file_type,storage_path,uploaded_by,uploaded_on,legacy_source,legacy_id)
      select deal_code,file_name,file_type,storage_path,uploaded_by,uploaded_on,'allocation_document',id from public.allocation_document
      on conflict(legacy_source,legacy_id) do nothing;
  end if;
end $migration$;

do $access$
declare t text;
begin
  foreach t in array array['deal_comment','deal_document'] loop
    execute format('alter table public.%I enable row level security',t);
    execute format('grant select,insert,update,delete on public.%I to authenticated',t);
    execute format('grant usage,select on sequence public.%I to authenticated',t||'_id_seq');
    execute format('drop policy if exists "app rw" on public.%I',t);
    execute format('create policy "app rw" on public.%I for all to authenticated using(true) with check(true)',t);
  end loop;
end $access$;
notify pgrst,'reload schema';
commit;
