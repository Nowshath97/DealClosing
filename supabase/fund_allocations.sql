-- Fund allocations: all 47 fields from NDC_FUND_ALLOCATIONS.
-- Run after allocation_tables.sql and normalize_client_accounts.sql,
-- then re-run save_allocation.sql before using the updated application.
-- tinyint(4) uses smallint to preserve legacy status codes; tinyint(1) uses boolean.
begin;
create unique index if not exists fund_closes_id_deal_unique on public.fund_closes(id,deal_code);
create table if not exists public.fund_allocations (
  id integer generated by default as identity primary key, -- Id
  deal_code varchar(50) references public.deal(deal_code), -- DealCode
  entity_id integer references public.entity("Id"), -- Entity
  allocation_pct numeric(19,14), -- AllocationPct
  amount_invested numeric(19,2), -- AmountInvested
  updated_by varchar(255), -- UpdatedBy
  updated_date_time timestamp without time zone, -- UpdatedDateTime
  capital_amount numeric(19,2), -- CapitalAmount
  credit_amount numeric(19,2), -- CreditAmount
  capital_call_amount numeric(19,2), -- CapitalCallAmount
  is_client_funding smallint, -- IsClientFunding
  veto_rights varchar(50), -- VetoRights
  are_wires_initiated smallint, -- AreWiresInitiated
  is_funded smallint, -- IsFunded
  funding_date date, -- FundingDate
  wires_initiated_date date, -- WiresInitiatedDate
  partial_amount numeric(19,2), -- PartialAmount
  veto_notes varchar(300), -- vetoNotes
  vetoed_date date, -- VetoedDate
  sf_nb_fund_association varchar(255), -- SfNBFundAssociation
  amount_usd numeric(19,2), -- AmountUSD
  amount_nb_fund_currency numeric(19,2), -- AmountNBFundCurrency
  veto_notification_date date, -- VetoNotificationDate
  veto_due_date date, -- VetoDueDate
  is_materials_sent smallint, -- IsMaterialsSent
  is_client_call smallint, -- IsClientCall
  materials_sent_date date, -- MaterialsSentDate
  client_call_date date, -- ClientCallDate
  is_client_reviewed smallint, -- IsClientReviewed
  veto_task_sent_date date, -- VetoTaskSentDate
  veto_task_delete_date date, -- VetoTaskDeleteDate
  subscribing_entity_id integer references public.entity("Id"), -- SubscribingEntity
  is_placeholder smallint, -- IsPlaceholder
  client_account varchar(255), -- ClientAccount
  is_capital_call_received smallint, -- IsCapitalCallReceived
  capital_call_received_date date, -- CapitalCallReceivedDate
  is_line_of_credit_drawn smallint, -- IsLineOfCreditDrawn
  line_of_credit_drawn_date date, -- LineOfCreditDrawnDate
  client_id integer references public.client_account(id), -- ClientId
  partial_amount_percentage numeric(19,14), -- PartialAmountPercentage
  docs_submitted_to_gp_date date, -- DocsSubmittedToGpDate
  exclusion_rights smallint, -- ExclusionRights
  is_pipco_team_populated boolean, -- IsPIPCOTeamPopulated
  original_pipco_amount numeric(19,2), -- OriginalPIPCOAmount
  initial_amount_invested numeric(19,2), -- InitialAmountInvested
  fund_close_id integer, -- FundCloseId
  expenses_amount numeric(19,2), -- ExpensesAmount
  constraint fund_allocations_close_deal_fk foreign key(fund_close_id,deal_code)
    references public.fund_closes(id,deal_code)
);
-- Current Initiate Allocations rows are deal-level (no close selected), one per entity.
-- Close-specific records are independent and are not replaced by deal-level saves.
create unique index if not exists fund_allocations_deal_entity_unique
  on public.fund_allocations(deal_code,entity_id) where fund_close_id is null;
create index if not exists fund_allocations_entity_idx on public.fund_allocations(entity_id);
create index if not exists fund_allocations_client_idx on public.fund_allocations(client_id);
create index if not exists fund_allocations_close_idx on public.fund_allocations(fund_close_id);
comment on column public.fund_allocations.client_account is 'Historical account label; client_id references the account master.';
comment on column public.fund_allocations.initial_amount_invested is 'First saved investment amount; later allocation edits do not overwrite it.';
comment on column public.fund_allocations.allocation_pct is 'Uses the existing screen percentage convention (0-100); no conversion to a fraction.';

-- Backfill existing screen allocations, without overwriting existing fund records.
insert into public.fund_allocations(deal_code,entity_id,allocation_pct,amount_invested,
  initial_amount_invested,expenses_amount,client_id,client_account,is_placeholder,updated_by,updated_date_time)
select l.deal_code,l.entity_id,l.percentage,l.adjusted_exposure,l.adjusted_exposure,l.expenses_amount,
  m.client_id,l.client_account,l.is_placeholder,'migration',localtimestamp
from public.allocation_line l left join public.client_entity_map m on m.id=l.account_map_id
where l.entity_id is not null
on conflict(deal_code,entity_id) where fund_close_id is null do nothing;

alter table public.fund_allocations enable row level security;
grant select,insert,update,delete on public.fund_allocations to authenticated;
grant usage,select on sequence public.fund_allocations_id_seq to authenticated;
drop policy if exists "app rw" on public.fund_allocations;
create policy "app rw" on public.fund_allocations for all to authenticated using(true) with check(true);
notify pgrst,'reload schema';
commit;
