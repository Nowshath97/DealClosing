-- Complete migration: run this entire file once before deploying the updated app.
-- Includes fund_closes schema, ID-preserving migration, task trigger and save RPC.
-- PostgreSQL / Supabase version of the supplied fund_closes schema.
-- Run in Supabase SQL Editor. Uses snake_case names, consistent with the app.
-- Each deal has its own close numbers: 1, 2, 3 ... . IDs remain globally unique.
-- This creates the close master; migration from allocation_close is a separate step.
begin;

create table if not exists public.fund_closes (
  id integer generated by default as identity primary key,
  deal_code varchar(50) not null references public.deal(deal_code),
  close_number integer,
  close_date date,
  is_active boolean,
  updated_date_time timestamp without time zone,
  updated_by varchar(255),
  has_wire_instructions_received boolean,
  target_funding_date_for_close date,
  close_status varchar(50),
  is_approved_to_close boolean,
  effective_date date,
  estimate_or_final_close varchar(50),
  is_funding_required varchar(10),
  is_partial_funding varchar(10),
  milestone varchar(50),
  is_lux_approved boolean,
  is_aggregator_used boolean,
  aggregator_id integer,
  reporting_period_end_date timestamp without time zone,
  gp_docs_execution_est_deadline date,
  actual_date_of_docs_to_gp date,
  created_on timestamptz not null default now(),
  editor_data jsonb not null default '{}'::jsonb
);

-- Existing fund_closes tables also receive the UI metadata columns.
alter table public.fund_closes add column if not exists created_on timestamptz not null default now(),
  add column if not exists editor_data jsonb not null default '{}'::jsonb;

-- The counter survives close deletion, so removed numbers are not reused.
-- Atomic UPSERT serializes concurrent allocations of numbers for the same deal.
create table if not exists public.fund_close_counters (
  deal_code varchar(50) primary key references public.deal(deal_code),
  last_number integer not null check(last_number > 0)
);
lock table public.fund_closes in access exclusive mode;

-- Validate existing explicit numbers before backfilling unnumbered closes.
do $validate$
begin
  if exists(select 1 from public.fund_closes where deal_code is null or btrim(deal_code)='') then
    raise exception 'Every fund close needs a deal_code before numbering.';
  end if;
  if exists(select 1 from public.fund_closes where close_number <= 0) then
    raise exception 'Existing close numbers must be positive.';
  end if;
  if exists(select 1 from public.fund_closes where close_number is not null
    group by deal_code,close_number having count(*) > 1) then
    raise exception 'Duplicate close numbers exist within a deal. Resolve before running this script.';
  end if;
end $validate$;

insert into public.fund_close_counters(deal_code,last_number)
select deal_code,max(close_number) from public.fund_closes
where close_number is not null group by deal_code
on conflict(deal_code) do update set last_number=greatest(fund_close_counters.last_number,excluded.last_number);

create or replace function public.assign_fund_close_number() returns trigger
language plpgsql security definer set search_path = pg_catalog, public as $$
begin
  if tg_op='UPDATE' then
    if new.id is distinct from old.id or new.deal_code is distinct from old.deal_code then
      raise exception 'A saved close ID and deal_code cannot be changed.';
    end if;
    if old.close_number is not null then
      if new.close_number is distinct from old.close_number then
        raise exception 'A saved close_number cannot be changed.';
      end if;
      return new;
    end if;
  end if;
  if new.deal_code is null or btrim(new.deal_code)='' then
    raise exception 'deal_code is required.';
  end if;
  if new.close_number is null then
    insert into public.fund_close_counters(deal_code,last_number) values(new.deal_code,1)
    on conflict(deal_code) do update set last_number=fund_close_counters.last_number+1
    returning last_number into new.close_number;
  else
    if new.close_number <= 0 then raise exception 'close_number must be positive.'; end if;
    -- Explicit numbers are supported for imports; advance the counter accordingly.
    insert into public.fund_close_counters(deal_code,last_number) values(new.deal_code,new.close_number)
    on conflict(deal_code) do update set last_number=greatest(fund_close_counters.last_number,excluded.last_number);
  end if;
  return new;
end $$;
revoke all on function public.assign_fund_close_number() from public;
drop trigger if exists assign_fund_close_number on public.fund_closes;
create trigger assign_fund_close_number before insert or update on public.fund_closes
for each row execute function public.assign_fund_close_number();

-- Number any pre-existing unnumbered records without changing explicit numbers.
-- On an unnumbered deal, assign 1, 2 ... in date/ID order.
do $backfill$
declare existing_close record;
begin
  for existing_close in select id from public.fund_closes where close_number is null
    order by deal_code,close_date nulls last,id loop
    update public.fund_closes set close_number=null where id=existing_close.id;
  end loop;
end $backfill$;
alter table public.fund_closes alter column deal_code set not null;
alter table public.fund_closes alter column close_number set not null;
create unique index if not exists fund_closes_deal_number_unique on public.fund_closes(deal_code,close_number);
create unique index if not exists fund_closes_id_deal_unique on public.fund_closes(id,deal_code);

alter table public.fund_closes enable row level security;
grant select,insert,update,delete on public.fund_closes to authenticated;
grant usage,select on sequence public.fund_closes_id_seq to authenticated;
drop policy if exists "app rw" on public.fund_closes;
create policy "app rw" on public.fund_closes for all to authenticated using(true) with check(true);
-- Counters are changed only by the numbering trigger, never directly by clients.
alter table public.fund_close_counters enable row level security;
revoke all on public.fund_close_counters from public,authenticated;

-- Transfer existing closes and every foreign key referencing their IDs.
do $move$
declare dependency record; definition text;
begin
  if to_regclass('public.allocation_close') is null then
    return;
  end if;
  if to_regclass('public.allocation_close_legacy') is not null then
    raise exception 'Both allocation_close and allocation_close_legacy exist. Inspect before migration.';
  end if;
  lock table public.allocation_close in access exclusive mode;
  if exists(select 1 from public.allocation_close a join public.fund_closes f on f.id=a.id
    where f.deal_code is distinct from a.deal_code or f.close_date is distinct from a.close_date
      or f.estimate_or_final_close is distinct from a.close_type) then
    raise exception 'Existing fund_closes IDs conflict with allocation_close. Reconcile these rows before migration.';
  end if;
  -- Older schemas may not yet have editor metadata.
  alter table public.allocation_close add column if not exists editor_data jsonb not null default '{}'::jsonb;
  if exists(select 1 from public.allocation_close a join public.fund_closes f on f.id=a.id
    where f.editor_data <> '{}'::jsonb and f.editor_data is distinct from a.editor_data) then
    raise exception 'Existing fund_closes editor metadata conflicts with allocation_close.';
  end if;
  insert into public.fund_closes(id,deal_code,close_date,estimate_or_final_close,is_active,created_on,editor_data)
    overriding system value
    select a.id,a.deal_code,a.close_date,a.close_type,true,a.created_on,a.editor_data
    from public.allocation_close a where not exists(select 1 from public.fund_closes f where f.id=a.id)
    order by a.deal_code,a.close_date nulls last,a.id;
  update public.fund_closes f set editor_data=a.editor_data
    from public.allocation_close a where f.id=a.id and f.editor_data='{}'::jsonb;
  perform setval(pg_get_serial_sequence('public.fund_closes','id'),coalesce((select max(id) from public.fund_closes),1),exists(select 1 from public.fund_closes));

  for dependency in select c.*,n.nspname,t.relname,pg_get_constraintdef(c.oid) as ddl
    from pg_constraint c join pg_class t on t.oid=c.conrelid join pg_namespace n on n.oid=t.relnamespace
    where c.contype='f' and c.confrelid='public.allocation_close'::regclass loop
    definition:=replace(replace(dependency.ddl,'REFERENCES public.allocation_close(', 'REFERENCES public.fund_closes('),'REFERENCES allocation_close(', 'REFERENCES public.fund_closes(');
    if definition=dependency.ddl then raise exception 'Unsupported foreign key %.',dependency.conname; end if;
    execute format('alter table %I.%I drop constraint %I',dependency.nspname,dependency.relname,dependency.conname);
    execute format('alter table %I.%I add constraint %I %s',dependency.nspname,dependency.relname,dependency.conname,definition);
  end loop;
  drop trigger if exists primary_close_finalize_task on public.allocation_close;
  alter table public.allocation_close rename to allocation_close_legacy;
end $move$;

-- Enable task rows to belong to one Primary deal close as well as a deal.
-- Run after allocation_tables.sql, from Supabase Dashboard -> SQL Editor.
-- Existing rows remain deal-level (close_id IS NULL).

alter table public.task
  add column if not exists close_id integer
  references public.fund_closes(id) on delete cascade;

create index if not exists task_deal_close_activity_idx
  on public.task (deal_code, close_id, activity_id);

-- One database-backed Finalize Allocations task per Primary close.
create or replace function public.ensure_primary_close_finalize_task() returns trigger
language plpgsql as $$
declare task_ref integer; activity_ref integer; status_ref integer;
begin
  if not exists(select 1 from public.deal d join public.ref_deal_type t on t.id=d.type
    where d.deal_code=new.deal_code and regexp_replace(lower(t.value),'[^a-z]','','g') in ('primary','primaries')) then return new; end if;
  select id into task_ref from public.ref_task_name where regexp_replace(lower(value),'[^a-z]','','g')='finalizeallocations' order by id limit 1;
  select id into status_ref from public.ref_task_status where regexp_replace(lower(value),'[^a-z]','','g')='notstarted' order by id limit 1;
  select activity_id into activity_ref from public.task_activity_map where task_id=task_ref and activity_id is not null limit 1;
  if activity_ref is null then
    select id into activity_ref from public.ref_deal_activity where regexp_replace(lower(value),'[^a-z]','','g') in ('allocations','dealallocations') order by id limit 1;
  end if;
  if task_ref is null or status_ref is null or activity_ref is null then
    raise exception 'Configure Finalize Allocations, Not Started and its task/activity mapping before saving Primary closes.';
  end if;
  perform pg_advisory_xact_lock(70621,new.id);
  if not exists(select 1 from public.task where close_id=new.id and deal_code=new.deal_code and task_id=task_ref) then
    insert into public.task(deal_code,close_id,task_id,activity_id,status,due_date)
      values(new.deal_code,new.id,task_ref,activity_ref,status_ref,new.close_date);
  end if;
  return new;
end $$;
drop trigger if exists primary_close_finalize_task on public.fund_closes;
create trigger primary_close_finalize_task after insert or update of close_date on public.fund_closes
  for each row execute function public.ensure_primary_close_finalize_task();
-- Backfill through the same trigger without duplicating existing task rows.
update public.fund_closes set close_date=close_date;
notify pgrst, 'reload schema';

-- Saves a whole allocation (header + lines + legal-name mapping + closes + comments + documents) in ONE transaction.
-- The app calls this from Save as draft / Save and exit / Initiate. Run allocation_tables.sql, fund_allocations.sql and deal_collaboration.sql first.
-- Run in Supabase Dashboard -> SQL Editor. Safe to re-run.
--
-- It replaces the deal's child rows each time, so what is on screen is exactly what is stored.

create or replace function public.save_allocation(p jsonb)
returns void
language plpgsql
as $$
declare
  v_deal   varchar := p->>'deal_code';
  h        jsonb   := p->'header';
  v_user   varchar := p->>'user';
  v_status varchar := coalesce(h->>'status', 'Draft');
  r        jsonb;
  v_line   int;
  v_updated int;
  v_ids    jsonb := '{}'::jsonb;   -- screen row ref -> allocation_line.id
begin
  if v_deal is null then
    raise exception 'deal_code is required';
  end if;

  insert into public.allocation (
    deal_code, funding_currency, total_adjusted_exposure, funding_required, partial_funding, expenses_pct, expenses_value,
    total_allocated, total_client_funding, calculation_override, aggregators_formed, status, initiated_by, initiated_on,
    created_by, modified_by, modified_on)
  values (
    v_deal, h->>'funding_currency', (h->>'total_adjusted_exposure')::numeric, (h->>'funding_required')::smallint, (h->>'partial_funding')::smallint,
    (h->>'expenses_pct')::numeric, (h->>'expenses_value')::numeric, (h->>'total_allocated')::numeric, (h->>'total_client_funding')::numeric,
    coalesce((h->>'calculation_override')::smallint, 0), coalesce((h->>'aggregators_formed')::smallint, 0), v_status,
    case when v_status = 'Initiated' then v_user end, case when v_status = 'Initiated' then now() end,
    v_user, v_user, now())
  on conflict (deal_code) do update set
    funding_currency        = excluded.funding_currency,
    total_adjusted_exposure = excluded.total_adjusted_exposure,
    funding_required        = excluded.funding_required,
    partial_funding         = excluded.partial_funding,
    expenses_pct            = excluded.expenses_pct,
    expenses_value          = excluded.expenses_value,
    total_allocated         = excluded.total_allocated,
    total_client_funding    = excluded.total_client_funding,
    calculation_override    = excluded.calculation_override,
    aggregators_formed      = excluded.aggregators_formed,
    status                  = excluded.status,
    initiated_by            = coalesce(public.allocation.initiated_by, excluded.initiated_by),
    initiated_on            = coalesce(public.allocation.initiated_on, excluded.initiated_on),
    modified_by             = v_user,
    modified_on             = now();

  -- Remove deal-level fund rows for entities explicitly removed from this screen.
  -- Close-specific allocations are managed separately.
  delete from public.fund_allocations f where f.deal_code=v_deal and f.fund_close_id is null
    and exists(select 1 from public.allocation_line old where old.deal_code=v_deal and old.entity_id=f.entity_id)
    and not exists(select 1 from jsonb_array_elements(coalesce(p->'lines','[]'::jsonb)) x where (x->>'entity_id')::int=f.entity_id);

  -- Replace editable children. Close IDs are preserved so close-scoped tasks remain attached when dates are edited.
  delete from public.allocation_line     where deal_code = v_deal;

  delete from public.fund_closes c
  where c.deal_code = v_deal
    and not exists (
      select 1 from jsonb_array_elements(coalesce(p->'closes', '[]'::jsonb)) x
      where x->>'id' ~ '^[0-9]+$' and (x->>'id')::int = c.id
    );

  for r in select * from jsonb_array_elements(coalesce(p->'lines', '[]'::jsonb)) loop
    insert into public.allocation_line (
      deal_code, line_no, account_map_id, client_account, entity_id, is_placeholder, adjusted_exposure, percentage, expenses_amount,
      expenses_overridden, client_funding, amgo_review_required, lux_review_required, additional_aml_review, client_veto)
    values (
      v_deal, (r->>'line_no')::smallint, (r->>'account_map_id')::int, coalesce(r->>'client_account', ''), (r->>'entity_id')::int,
      coalesce((r->>'is_placeholder')::smallint, 0), (r->>'adjusted_exposure')::numeric, (r->>'percentage')::numeric, (r->>'expenses_amount')::numeric,
      coalesce((r->>'expenses_overridden')::smallint, 0), (r->>'client_funding')::numeric, (r->>'amgo_review_required')::smallint,
      (r->>'lux_review_required')::smallint, (r->>'additional_aml_review')::smallint, (r->>'client_veto')::smallint)
    returning id into v_line;
    v_ids := v_ids || jsonb_build_object(r->>'ref', v_line);
    if nullif(r->>'entity_id','') is not null then
      insert into public.fund_allocations(deal_code,entity_id,allocation_pct,amount_invested,
        initial_amount_invested,expenses_amount,client_id,client_account,is_placeholder,updated_by,updated_date_time)
      values(v_deal,(r->>'entity_id')::int,(r->>'percentage')::numeric,(r->>'adjusted_exposure')::numeric,
        (r->>'adjusted_exposure')::numeric,(r->>'expenses_amount')::numeric,
        (select client_id from public.client_entity_map where id=(r->>'account_map_id')::int),
        r->>'client_account',(r->>'is_placeholder')::smallint,v_user,localtimestamp)
      on conflict(deal_code,entity_id) where fund_close_id is null do update set
        allocation_pct=excluded.allocation_pct,amount_invested=excluded.amount_invested,
        expenses_amount=excluded.expenses_amount,client_id=excluded.client_id,client_account=excluded.client_account,
        is_placeholder=excluded.is_placeholder,updated_by=excluded.updated_by,updated_date_time=excluded.updated_date_time;
    end if;
  end loop;

  for r in select * from jsonb_array_elements(coalesce(p->'legal_map', '[]'::jsonb)) loop
    insert into public.allocation_legal_map (deal_code, line_id, investment_legal_name, allocation_amount)
    values (v_deal, (v_ids->>(r->>'line_ref'))::int, r->>'investment_legal_name', (r->>'allocation_amount')::numeric);
  end loop;

  for r in select * from jsonb_array_elements(coalesce(p->'closes', '[]'::jsonb)) loop
    v_updated := 0;
    if r->>'id' ~ '^[0-9]+$' then
      update public.fund_closes
      set close_date = (r->>'close_date')::date, estimate_or_final_close = nullif(r->>'close_type', '')
      where id = (r->>'id')::int and deal_code = v_deal;
      get diagnostics v_updated = row_count;
    end if;
    if v_updated = 0 then
      insert into public.fund_closes (deal_code, close_date, estimate_or_final_close)
      values (v_deal, (r->>'close_date')::date, nullif(r->>'close_type', ''));
    end if;
  end loop;

  -- Deal collaboration is shared across tasks. Never replace all deal records on save.
  for r in select * from jsonb_array_elements(coalesce(p->'comments','[]'::jsonb)) loop
    if nullif(r->>'id','') is null then
      insert into public.deal_comment(deal_code,client_ref,comment_text,created_by,created_on)
      values(v_deal,r->>'client_ref',r->>'comment_text',coalesce(r->>'created_by',v_user),coalesce((r->>'created_on')::timestamptz,now()))
      on conflict(deal_code,client_ref) do nothing;
    end if;
  end loop;
  delete from public.deal_document d where d.deal_code=v_deal
    and d.id in(select value::int from jsonb_array_elements_text(coalesce(p->'removed_document_ids','[]'::jsonb)));
  for r in select * from jsonb_array_elements(coalesce(p->'documents','[]'::jsonb)) loop
    if nullif(r->>'id','') is null then
      insert into public.deal_document(deal_code,client_ref,file_name,file_type,uploaded_by,uploaded_on)
      values(v_deal,r->>'client_ref',r->>'file_name',r->>'file_type',coalesce(r->>'uploaded_by',v_user),coalesce((r->>'uploaded_on')::timestamptz,now()))
      on conflict(deal_code,client_ref) do nothing;
    end if;
  end loop;
end;
$$;

grant execute on function public.save_allocation(jsonb) to authenticated;

notify pgrst, 'reload schema';

notify pgrst,'reload schema';
commit;
