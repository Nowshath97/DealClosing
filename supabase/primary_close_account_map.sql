-- Stores which client accounts are included in each Primary-deal close.
-- Run after allocation_tables.sql in Supabase Dashboard -> SQL Editor.
create table if not exists public.allocation_close_account (
  id           integer generated by default as identity primary key,
  deal_code    varchar(50) not null references public.allocation(deal_code) on delete cascade,
  close_id     integer not null references public.fund_closes(id) on delete cascade,
  account_name varchar(255) not null,
  nb_age_vintage_year varchar(20),
  ic_approval boolean,
  ic_approved_date date,
  allocation_funding_currency numeric(20,2),
  allocation_usd numeric(20,2),
  receive_signoff_from_pm boolean,
  subject_to_client_review varchar(50),
  client_review_information text,
  client_approved boolean,
  created_on   timestamptz not null default now(),
  constraint allocation_close_account_unique unique (close_id, account_name)
);

alter table public.allocation_close_account
  add column if not exists nb_age_vintage_year varchar(20),
  add column if not exists ic_approval boolean,
  add column if not exists ic_approved_date date,
  add column if not exists allocation_funding_currency numeric(20,2),
  add column if not exists allocation_usd numeric(20,2),
  add column if not exists receive_signoff_from_pm boolean,
  add column if not exists subject_to_client_review varchar(50),
  add column if not exists client_review_information text,
  add column if not exists client_approved boolean;

create index if not exists allocation_close_account_deal_idx
  on public.allocation_close_account (deal_code, close_id);

alter table public.allocation_close_account enable row level security;
grant select, insert, update, delete on public.allocation_close_account to authenticated;
drop policy if exists "app rw" on public.allocation_close_account;
create policy "app rw" on public.allocation_close_account
  for all to authenticated using (true) with check (true);

-- Close-screen funding settings and per-account entity/tranche mappings.
alter table public.fund_closes
  add column if not exists editor_data jsonb not null default '{}'::jsonb;

notify pgrst, 'reload schema';
